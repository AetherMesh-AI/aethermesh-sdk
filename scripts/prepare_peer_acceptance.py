"""Prepare public fixture bytes and an unrun worksheet; no network or identities."""

from __future__ import annotations

import argparse
import json
import os
import sys
from pathlib import Path
from typing import Any

from aethermesh_core.network import TransferStore


def prepare(output: Path, project_id: str) -> dict[str, Any]:
    """Write one new private directory in a trusted, stable physical parent.

    Partial output is retained on I/O failure; no overwrite, deletion, rollback
    or filesystem durability guarantee is provided. Generated bytes are public.
    """
    data = b"".join(bytes([index]) * 32768 for index in range(256))
    manifest = TransferStore(project_id, data, max_served_bytes=0).manifest
    target = output.absolute()
    if target != target.resolve() or target.name in {"", ".", ".."}:
        raise ValueError("use a new physical directory")
    worksheet: dict[str, Any] = {
        "worksheet_version": 1,
        "acceptance_status": "not_run",
        "network_activity_performed": False,
        "two_computer_acceptance": False,
        "publisher_authorized": False,
        "fixture": {
            "format": "public-distinct-chunks-v1",
            "filename": "fixture.bin",
            "project": project_id,
            "size": manifest.size,
            "sha256": manifest.sha256,
            "manifest_filename": "manifest.json",
            "manifest_sha256": manifest.digest,
            "chunk_count": len(manifest.chunks),
        },
        "required_inputs": dict.fromkeys(
            (
                "machine_a_operator_os_python",
                "machine_b_operator_os_python",
                "operator_confirmation_of_distinct_computers",
                "access_and_installation_approval",
                "sdk_wheel_sha256",
                "approved_dependency_artifacts",
                "existing_identity_locations_local_only",
                "verified_public_pins",
                "approved_interface_port_and_san",
                "foreground_listener_and_client_permission",
                "storage_and_cleanup_owner",
            )
        ),
        "proposed_plan_not_authorization": {
            "per_invocation_timeout_seconds": 30,
            "server_lifetime_byte_budget": 33554432,
            "interrupt_after_verified_chunks": 3,
            "expected_missing_chunks_if_exactly_three_are_preserved": 253,
        },
        "observations": {
            name: {
                "status": "not_run",
                "started_at_utc": None,
                "ended_at_utc": None,
                "exit_code": None,
                "sanitized_stdout": None,
                "sanitized_stderr": None,
                "notes": None,
            }
            for name in (
                "environment",
                "authenticated_status",
                "wrong_pin",
                "wrong_project",
                "transfer_integrity",
                "interruption_and_process_restart_resume",
                "stopped_service_and_explicit_reconnect",
                "optional_alternatives",
                "optional_reverse_direction",
            )
        },
    }
    files = {
        "fixture.bin": data,
        "manifest.json": manifest.encode(),
        "evidence.json": (
            json.dumps(worksheet, indent=2, sort_keys=True) + "\n"
        ).encode(),
    }
    target.mkdir(mode=0o700)
    for name, content in files.items():
        descriptor = os.open(target / name, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        with os.fdopen(descriptor, "wb") as stream:
            stream.write(content)
    return worksheet


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--project", required=True)
    parser.add_argument(
        "--output", required=True, type=Path, help="new physical directory"
    )
    args = parser.parse_args()
    try:
        worksheet = prepare(args.output, args.project)
    except (OSError, ValueError):
        print(
            "Unable to prepare fixture; select a valid project and new owned physical directory.",
            file=sys.stderr,
        )
        return 1
    print(
        json.dumps(
            {"fixture": worksheet["fixture"], "acceptance_status": "not_run"},
            sort_keys=True,
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
